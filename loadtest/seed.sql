-- Load test data set (IO-78): 500 users x 10 projects x 5 versions.
-- Versions 1-4 are submitted (55 answers, 55 stored results), version 5 is
-- the latest draft with 55 complete answers. Run once on a migrated database
-- that already holds the catalogue (the migrate service seeds it):
--   psql -v ON_ERROR_STOP=1 -v hash="'<argon2id hash>'" -f seed.sql
-- Every user has the same password, see loadtest/run.sh.
-- Re-running fails on the unique e-mail, so reset the stack first.
BEGIN;

INSERT INTO account (id, email, password_hash, organisation, role, status,
                     pseudonym, terms_accepted_at)
SELECT gen_random_uuid(), 'lt-user-' || n || '@loadtest.invalid', :hash,
       'Load test', 'user', 'active', 'lt-pseudo-' || n, now()
FROM generate_series(1, 500) n;

CREATE TEMP TABLE lt_project ON COMMIT DROP AS
SELECT gen_random_uuid() AS id, a.id AS owner_id, p
FROM account a
CROSS JOIN generate_series(1, 10) p
WHERE a.email::text LIKE 'lt-user-%@loadtest.invalid';

INSERT INTO project (id, owner_id, name, nickname, island_code, type_code,
                     start_date, end_date, value_baht, progress_pct,
                     description, created_at)
SELECT id, owner_id, 'Load project ' || p, 'P' || lpad(p::text, 2, '0'),
       (SELECT code FROM island WHERE sort_no = 1 + p % 7),
       (SELECT code FROM project_type WHERE sort_no = 1 + p % 5),
       DATE '2026-01-01', DATE '2027-01-01', 1000000 * p, 10 * p,
       'Generated by loadtest/seed.sql',
       now() - make_interval(mins => p)
FROM lt_project;

CREATE TEMP TABLE lt_version ON COMMIT DROP AS
SELECT gen_random_uuid() AS id, lp.id AS project_id, v, lp.p
FROM lt_project lp
CROSS JOIN generate_series(1, 5) v;

INSERT INTO assessment_version (id, project_id, version_no, status,
    submission_no, snap_value_baht, snap_start_date, snap_end_date,
    snap_score_decimals, snap_rm_decimals, progress_at_submit, created_at,
    submitted_at)
SELECT lv.id, lv.project_id, lv.v,
       CASE WHEN lv.v < 5 THEN 'submitted'::version_status ELSE 'draft' END,
       CASE WHEN lv.v < 5 THEN 1 ELSE 0 END,
       pr.value_baht, pr.start_date, pr.end_date, 2, 3,
       CASE WHEN lv.v < 5 THEN pr.progress_pct END,
       now() - make_interval(days => 10 - lv.v),
       CASE WHEN lv.v < 5 THEN now() - make_interval(days => 9 - lv.v) END
FROM lt_version lv
JOIN project pr ON pr.id = lv.project_id;

INSERT INTO version_rl_threshold (version_id, indicator_code, a, b, c, d, e)
SELECT lv.id, i.code, i.a, i.b, i.c, i.d, i.e
FROM lt_version lv CROSS JOIN indicator i;

INSERT INTO version_impact_threshold (version_id, impact_code, a, b, c, d, e)
SELECT lv.id, t.code, t.a, t.b, t.c, t.d, t.e
FROM lt_version lv CROSS JOIN impact_table t;

-- 55 complete answers per version: x, y1 and y2 in percent, one y3 option.
INSERT INTO answer (version_id, indicator_code, x, y1_value, y1_unit,
                    y2_value, y2_unit)
SELECT lv.id, i.code, (ascii(right(i.code, 1)) + lv.p) % 40,
       (lv.p * 3) % 60, 'percent', (lv.p * 5) % 60, 'percent'
FROM lt_version lv CROSS JOIN indicator i;

INSERT INTO answer_y3 (version_id, indicator_code, option_code)
SELECT version_id, indicator_code, 'B' FROM answer;

-- Stored results of the submitted versions (read as stored, never recomputed).
CREATE TEMP TABLE lt_result ON COMMIT DROP AS
SELECT a.version_id, a.indicator_code, a.x,
       1 + (ascii(right(a.indicator_code, 1)) + lv.v) % 5 AS rl,
       1 + (lv.p + lv.v) % 5 AS ri_c,
       1 + (lv.p * 2 + lv.v) % 5 AS ri_t,
       1 + (ascii(left(a.indicator_code, 1)) + lv.p) % 5 AS ri_e
FROM answer a
JOIN lt_version lv ON lv.id = a.version_id
WHERE lv.v < 5;

INSERT INTO risk_result (version_id, indicator_code, x, y1_pct, y2_pct, rl,
                         ri_c, ri_t, ri_e, ri_max, rm, level)
SELECT version_id, indicator_code, x, 10, 10, rl, ri_c, ri_t, ri_e,
       GREATEST(ri_c, ri_t, ri_e),
       (rl + GREATEST(ri_c, ri_t, ri_e)) / 2.0,
       CASE WHEN (rl + GREATEST(ri_c, ri_t, ri_e)) / 2.0 < 1.5 THEN 'VL'::risk_level
            WHEN (rl + GREATEST(ri_c, ri_t, ri_e)) / 2.0 < 2.5 THEN 'L'
            WHEN (rl + GREATEST(ri_c, ri_t, ri_e)) / 2.0 < 3.5 THEN 'M'
            WHEN (rl + GREATEST(ri_c, ri_t, ri_e)) / 2.0 < 4.5 THEN 'H'
            ELSE 'VH' END
FROM lt_result;

INSERT INTO result_advice_list (version_id, indicator_code, list)
SELECT version_id, indicator_code, 'RL'
FROM risk_result WHERE level IN ('H', 'VH');

COMMIT;
ANALYZE;
